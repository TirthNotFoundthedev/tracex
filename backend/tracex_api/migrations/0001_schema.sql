-- TraceX schema. Runs as tracex_migrator, which owns every object. Synthetic data only.
-- docs/architecture.md sections 3 to 5 describe each table.

CREATE TABLE states (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    name text NOT NULL UNIQUE
);

CREATE TABLE districts (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    state_id uuid NOT NULL REFERENCES states (id),
    name text NOT NULL,
    code smallint NOT NULL UNIQUE CHECK (code BETWEEN 1 AND 9),
    UNIQUE (state_id, name)
);

CREATE TABLE users (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    username text NOT NULL UNIQUE CHECK (username = lower(username)),
    display_name text NOT NULL,
    role text NOT NULL CHECK (role IN ('JUNIOR', 'INVESTIGATOR', 'SUPERVISOR', 'SENIOR', 'ADMIN')),
    district_id uuid REFERENCES districts (id),
    active boolean NOT NULL DEFAULT true,
    authz_version integer NOT NULL DEFAULT 1,
    password_hash text,
    CHECK (
        (role IN ('JUNIOR', 'INVESTIGATOR', 'SUPERVISOR') AND district_id IS NOT NULL)
        OR (role IN ('SENIOR', 'ADMIN') AND district_id IS NULL)
    )
);

CREATE TABLE user_coverage (
    id bigserial PRIMARY KEY,
    user_id uuid NOT NULL REFERENCES users (id),
    state_id uuid REFERENCES states (id),
    district_id uuid REFERENCES districts (id),
    all_states boolean NOT NULL DEFAULT false,
    CHECK (
        (state_id IS NOT NULL)::int + (district_id IS NOT NULL)::int + all_states::int = 1
    )
);

CREATE TABLE sessions (
    sid uuid PRIMARY KEY,
    user_id uuid NOT NULL REFERENCES users (id),
    created_at timestamptz NOT NULL,
    expires_at timestamptz NOT NULL,
    revoked_at timestamptz,
    revoke_reason text
);

CREATE TABLE refresh_tokens (
    jti uuid PRIMARY KEY,
    sid uuid NOT NULL REFERENCES sessions (sid) ON DELETE CASCADE,
    issued_at timestamptz NOT NULL,
    used_at timestamptz,
    replaced_by uuid
);

CREATE TABLE login_attempts (
    id bigserial PRIMARY KEY,
    key text NOT NULL,
    at timestamptz NOT NULL
);
CREATE INDEX login_attempts_key_at ON login_attempts (key, at);

CREATE TABLE cases (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    case_number text NOT NULL,
    title text NOT NULL DEFAULT '',
    district_id uuid NOT NULL REFERENCES districts (id),
    opened_on date NOT NULL DEFAULT CURRENT_DATE,
    serial integer GENERATED BY DEFAULT AS IDENTITY,
    engine_case_id text NOT NULL UNIQUE,
    UNIQUE (district_id, case_number)
);

CREATE TABLE case_assignments (
    case_id uuid NOT NULL REFERENCES cases (id),
    user_id uuid NOT NULL REFERENCES users (id),
    assigned_at timestamptz NOT NULL DEFAULT now(),
    active boolean NOT NULL DEFAULT true,
    PRIMARY KEY (case_id, user_id)
);

CREATE TABLE upload_batches (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    uploaded_by uuid NOT NULL REFERENCES users (id),
    file_name text NOT NULL,
    file_sha256 text NOT NULL,
    byte_count integer NOT NULL,
    status text NOT NULL CHECK (status IN ('WAITING', 'READING', 'DONE', 'FAILED')),
    error_code text,
    case_id uuid REFERENCES cases (id),
    document_count integer NOT NULL DEFAULT 0,
    created_at timestamptz NOT NULL DEFAULT now(),
    matched_run_id uuid
);

CREATE TABLE documents (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    case_id uuid NOT NULL REFERENCES cases (id),
    doc_type text NOT NULL,
    batch_id uuid NOT NULL REFERENCES upload_batches (id),
    file_name text NOT NULL,
    UNIQUE (case_id, file_name)
);

CREATE TABLE document_lines (
    document_id uuid NOT NULL REFERENCES documents (id),
    line_no integer NOT NULL CHECK (line_no >= 1),
    page integer,
    text text NOT NULL,
    PRIMARY KEY (document_id, line_no)
);

CREATE TABLE entities (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    case_id uuid NOT NULL REFERENCES cases (id),
    engine_entity_id text NOT NULL UNIQUE,
    type text NOT NULL CHECK (type IN ('PERSON', 'ORG', 'PHONE', 'ACCOUNT', 'VEHICLE')),
    normalized_value text NOT NULL,
    display_value text NOT NULL,
    raw_text text NOT NULL,
    extraction_confidence numeric(4, 3) NOT NULL,
    source_document_id uuid NOT NULL REFERENCES documents (id),
    source_line integer NOT NULL,
    facts jsonb NOT NULL DEFAULT '[]'::jsonb
);
CREATE INDEX entities_case ON entities (case_id);
CREATE INDEX entities_value ON entities (type, normalized_value);

CREATE TABLE entity_mentions (
    id bigserial PRIMARY KEY,
    entity_id uuid NOT NULL REFERENCES entities (id),
    document_id uuid NOT NULL REFERENCES documents (id),
    line integer NOT NULL,
    UNIQUE (entity_id, document_id, line)
);

CREATE TABLE match_runs (
    id uuid PRIMARY KEY,
    started_at timestamptz NOT NULL,
    finished_at timestamptz,
    triggered_by uuid REFERENCES users (id),
    input_case_ids uuid[] NOT NULL DEFAULT '{}',
    input_batch_ids uuid[] NOT NULL DEFAULT '{}',
    ruleset_version text NOT NULL,
    thresholds_version integer NOT NULL,
    counts jsonb NOT NULL DEFAULT '{}'::jsonb,
    oversized_block_count integer NOT NULL DEFAULT 0,
    status text NOT NULL CHECK (status IN ('RUNNING', 'SUCCEEDED', 'FAILED')),
    error_code text
);
CREATE UNIQUE INDEX match_runs_one_running ON match_runs ((true)) WHERE status = 'RUNNING';

CREATE TABLE links (
    link_id uuid PRIMARY KEY,
    entity_a_id uuid NOT NULL REFERENCES entities (id),
    entity_b_id uuid NOT NULL REFERENCES entities (id),
    case_a_id uuid NOT NULL REFERENCES cases (id),
    case_b_id uuid NOT NULL REFERENCES cases (id),
    entity_type text NOT NULL,
    state text NOT NULL CHECK (
        state IN ('AUTO', 'SUGGESTED', 'CONFIRMED', 'REJECTED', 'UNDONE', 'WITHDRAWN')
    ),
    band text NOT NULL CHECK (band IN ('HIGH', 'MEDIUM', 'LOW')),
    score numeric(4, 1) NOT NULL,
    thresholds_version integer NOT NULL,
    ruleset_version text NOT NULL,
    match_run_id uuid REFERENCES match_runs (id),
    explanation jsonb NOT NULL,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    CHECK (entity_a_id < entity_b_id),
    CHECK (case_a_id <> case_b_id)
);
CREATE UNIQUE INDEX links_live_pair ON links (entity_a_id, entity_b_id) WHERE state <> 'WITHDRAWN';
CREATE INDEX links_entity_a ON links (entity_a_id);
CREATE INDEX links_entity_b ON links (entity_b_id);

CREATE TABLE link_history (
    id bigserial PRIMARY KEY,
    link_id uuid NOT NULL REFERENCES links (link_id),
    from_state text,
    to_state text,
    actor_kind text NOT NULL CHECK (actor_kind IN ('ENGINE', 'USER')),
    actor_user_id uuid REFERENCES users (id),
    at timestamptz NOT NULL,
    reason_code text,
    reason_text text,
    match_run_id uuid,
    decision_id uuid
);
CREATE INDEX link_history_link ON link_history (link_id, id);

CREATE TABLE decision_outbox (
    decision_id uuid PRIMARY KEY,
    link_id uuid NOT NULL REFERENCES links (link_id),
    expected_from text NOT NULL,
    to_state text NOT NULL,
    actor_user_id uuid NOT NULL REFERENCES users (id),
    reason_code text,
    reason_text text,
    created_at timestamptz NOT NULL DEFAULT now(),
    acked_at timestamptz
);

CREATE TABLE link_cited_lines (
    link_id uuid NOT NULL REFERENCES links (link_id),
    document_id uuid NOT NULL REFERENCES documents (id),
    line_from integer NOT NULL,
    line_to integer NOT NULL,
    PRIMARY KEY (link_id, document_id, line_from, line_to)
);

CREATE TABLE stubs (
    stub_id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    holder_user_id uuid NOT NULL REFERENCES users (id),
    link_id uuid NOT NULL REFERENCES links (link_id),
    near_entity_id uuid NOT NULL REFERENCES entities (id),
    created_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (holder_user_id, link_id)
);

CREATE TABLE access_requests (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    requester_id uuid NOT NULL REFERENCES users (id),
    stub_id uuid NOT NULL REFERENCES stubs (stub_id),
    link_id uuid NOT NULL REFERENCES links (link_id),
    near_case_id uuid NOT NULL REFERENCES cases (id),
    far_case_id uuid NOT NULL REFERENCES cases (id),
    reason text NOT NULL CHECK (char_length(reason) BETWEEN 10 AND 500),
    state text NOT NULL CHECK (state IN ('PENDING', 'APPROVED', 'DENIED', 'WITHDRAWN', 'EXPIRED')),
    requested_at timestamptz NOT NULL,
    expires_at timestamptz NOT NULL,
    decided_by uuid REFERENCES users (id),
    decided_at timestamptz,
    decision_note text CHECK (char_length(decision_note) <= 200),
    CHECK (decided_by IS NULL OR decided_by <> requester_id)
);
CREATE UNIQUE INDEX access_requests_one_pending ON access_requests (stub_id) WHERE state = 'PENDING';

CREATE TABLE access_grants (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    request_id uuid NOT NULL UNIQUE REFERENCES access_requests (id),
    holder_id uuid NOT NULL REFERENCES users (id),
    link_id uuid NOT NULL REFERENCES links (link_id),
    far_entity_id uuid NOT NULL REFERENCES entities (id),
    far_case_id uuid NOT NULL REFERENCES cases (id),
    state text NOT NULL CHECK (state IN ('ACTIVE', 'EXPIRED', 'REVOKED')),
    starts_at timestamptz NOT NULL,
    expires_at timestamptz NOT NULL,
    closed_at timestamptz,
    close_cause text CHECK (close_cause IN ('MANUAL', 'ROLE_CHANGE', 'LINK_CLOSED', 'EVIDENCE_CHANGED', 'TIME')),
    role_at_grant text NOT NULL
);

CREATE TABLE grant_line_ranges (
    grant_id uuid NOT NULL REFERENCES access_grants (id),
    document_id uuid NOT NULL REFERENCES documents (id),
    line_from integer NOT NULL,
    line_to integer NOT NULL,
    PRIMARY KEY (grant_id, document_id, line_from, line_to)
);

CREATE TABLE pending_changes (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    kind text NOT NULL,
    subject_user_id uuid REFERENCES users (id),
    old_value jsonb,
    new_value jsonb NOT NULL,
    proposer_id uuid NOT NULL REFERENCES users (id),
    change_hash bytea NOT NULL CHECK (octet_length(change_hash) = 32),
    state text NOT NULL CHECK (state IN ('PENDING', 'APPROVED', 'DENIED')),
    decider_id uuid REFERENCES users (id),
    decided_at timestamptz,
    approved_hash bytea,
    applied boolean NOT NULL DEFAULT false,
    proposed_at timestamptz NOT NULL,
    subject_district_ids uuid[] NOT NULL DEFAULT '{}',
    needs_all_states boolean NOT NULL DEFAULT false,
    CHECK (decider_id IS NULL OR decider_id <> proposer_id),
    CHECK (decider_id IS NULL OR subject_user_id IS NULL OR decider_id <> subject_user_id)
);

CREATE TABLE threshold_versions (
    thresholds_version integer PRIMARY KEY,
    high_min numeric(5, 1) NOT NULL,
    medium_min numeric(5, 1) NOT NULL,
    approved_change_id uuid REFERENCES pending_changes (id),
    effective_at timestamptz NOT NULL DEFAULT now(),
    CHECK (high_min BETWEEN 70 AND 100),
    CHECK (medium_min >= 30 AND medium_min <= high_min - 10)
);

CREATE TABLE audit_log (
    seq bigint PRIMARY KEY,
    event_id uuid NOT NULL UNIQUE,
    occurred_at timestamptz NOT NULL,
    event_type text NOT NULL,
    outcome text NOT NULL CHECK (outcome IN ('SUCCESS', 'DENIED', 'FAILED')),
    actor_kind text NOT NULL CHECK (actor_kind IN ('USER', 'SYSTEM', 'ANONYMOUS')),
    actor_user_id uuid,
    actor_role text,
    actor_district_id uuid,
    reason_code text,
    refs jsonb NOT NULL DEFAULT '[]'::jsonb,
    target_type text,
    target_id text,
    resolved_target text,
    detail jsonb NOT NULL DEFAULT '{}'::jsonb,
    session_id uuid,
    request_id uuid,
    client_ip inet,
    row_nonce bytea NOT NULL CHECK (octet_length(row_nonce) = 16),
    prev_hash bytea NOT NULL CHECK (octet_length(prev_hash) = 32),
    row_hash bytea NOT NULL CHECK (octet_length(row_hash) = 32),
    CONSTRAINT audit_log_unresolved_has_no_refs CHECK (
        target_type IS DISTINCT FROM 'UNRESOLVED' OR refs = '[]'::jsonb
    )
);

CREATE TABLE audit_detail_key_owner (
    event_type text NOT NULL,
    detail_key text NOT NULL,
    owner_ref text NOT NULL,
    PRIMARY KEY (event_type, detail_key)
);

CREATE FUNCTION audit_log_block_change() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'audit_log is append only (% blocked)', TG_OP;
END;
$$;

CREATE TRIGGER audit_log_no_row_change
    BEFORE UPDATE OR DELETE ON audit_log
    FOR EACH ROW EXECUTE FUNCTION audit_log_block_change();

CREATE TRIGGER audit_log_no_truncate
    BEFORE TRUNCATE ON audit_log
    FOR EACH STATEMENT EXECUTE FUNCTION audit_log_block_change();

CREATE FUNCTION audit_log_known_detail_keys() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    unknown text;
BEGIN
    SELECT k INTO unknown
    FROM jsonb_object_keys(NEW.detail) AS k
    WHERE NOT EXISTS (
        SELECT 1 FROM audit_detail_key_owner o
        WHERE o.event_type = NEW.event_type AND o.detail_key = k
    )
    LIMIT 1;
    IF unknown IS NOT NULL THEN
        RAISE EXCEPTION 'audit detail key not allowed for %', NEW.event_type
            USING ERRCODE = 'check_violation';
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER audit_log_refs_cover_detail
    BEFORE INSERT ON audit_log
    FOR EACH ROW EXECUTE FUNCTION audit_log_known_detail_keys();

CREATE FUNCTION apply_change(change uuid) RETURNS void
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp AS $$
DECLARE
    c pending_changes%ROWTYPE;
    new_user uuid;
    cov jsonb;
    next_version integer;
BEGIN
    SELECT * INTO c FROM pending_changes WHERE id = change FOR UPDATE;
    IF NOT FOUND OR c.state <> 'APPROVED' OR c.applied
       OR c.approved_hash IS DISTINCT FROM c.change_hash THEN
        RAISE EXCEPTION 'change % is not approved for application', change;
    END IF;
    IF c.kind = 'USER_CREATE' THEN
        INSERT INTO users (username, display_name, role, district_id)
        VALUES (
            c.new_value ->> 'username', c.new_value ->> 'display_name', c.new_value ->> 'role',
            NULLIF(c.new_value ->> 'district_id', '')::uuid
        ) RETURNING id INTO new_user;
        FOR cov IN SELECT * FROM jsonb_array_elements(coalesce(c.new_value -> 'coverage_rows', '[]'::jsonb)) LOOP
            INSERT INTO user_coverage (user_id, state_id, district_id, all_states)
            VALUES (
                new_user, NULLIF(cov ->> 'state_id', '')::uuid,
                NULLIF(cov ->> 'district_id', '')::uuid, coalesce((cov ->> 'all_states')::boolean, false)
            );
        END LOOP;
    ELSIF c.kind = 'USER_ENABLE' THEN
        UPDATE users SET active = true, authz_version = authz_version + 1 WHERE id = c.subject_user_id;
    ELSIF c.kind = 'USER_DISABLE' THEN
        UPDATE users SET active = false, authz_version = authz_version + 1 WHERE id = c.subject_user_id;
    ELSIF c.kind = 'USER_ROLE' THEN
        UPDATE users SET role = c.new_value ->> 'role', authz_version = authz_version + 1
        WHERE id = c.subject_user_id;
    ELSIF c.kind = 'USER_JURISDICTION' THEN
        UPDATE users SET district_id = NULLIF(c.new_value ->> 'district_id', '')::uuid,
            authz_version = authz_version + 1
        WHERE id = c.subject_user_id;
        DELETE FROM user_coverage WHERE user_id = c.subject_user_id;
        FOR cov IN SELECT * FROM jsonb_array_elements(coalesce(c.new_value -> 'coverage_rows', '[]'::jsonb)) LOOP
            INSERT INTO user_coverage (user_id, state_id, district_id, all_states)
            VALUES (
                c.subject_user_id, NULLIF(cov ->> 'state_id', '')::uuid,
                NULLIF(cov ->> 'district_id', '')::uuid, coalesce((cov ->> 'all_states')::boolean, false)
            );
        END LOOP;
    ELSIF c.kind = 'ASSIGNMENT_ADD' THEN
        INSERT INTO case_assignments (case_id, user_id, active)
        VALUES ((c.new_value ->> 'case_id')::uuid, c.subject_user_id, true)
        ON CONFLICT (case_id, user_id) DO UPDATE SET active = true;
        UPDATE users SET authz_version = authz_version + 1 WHERE id = c.subject_user_id;
    ELSIF c.kind = 'ASSIGNMENT_REMOVE' THEN
        UPDATE case_assignments SET active = false
        WHERE case_id = (c.new_value ->> 'case_id')::uuid AND user_id = c.subject_user_id;
        UPDATE users SET authz_version = authz_version + 1 WHERE id = c.subject_user_id;
    ELSIF c.kind = 'THRESHOLDS' THEN
        SELECT coalesce(max(thresholds_version), 0) + 1 INTO next_version FROM threshold_versions;
        INSERT INTO threshold_versions (thresholds_version, high_min, medium_min, approved_change_id)
        VALUES (
            next_version, (c.new_value ->> 'high_min')::numeric, (c.new_value ->> 'medium_min')::numeric,
            c.id
        );
    ELSE
        RAISE EXCEPTION 'unknown change kind %', c.kind;
    END IF;
    UPDATE pending_changes SET applied = true WHERE id = c.id;
END;
$$;

INSERT INTO threshold_versions (thresholds_version, high_min, medium_min) VALUES (1, 80, 45);
