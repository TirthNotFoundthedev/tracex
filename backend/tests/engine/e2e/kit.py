"""The data kit end to end: generate, load batches, run, export and score.

The kit is generated by its own CLI (`python -m datakit`, standard library only) into a temp
directory and scored by its reference scorer, both run as subprocesses from `data-kit/`, so
nothing here copies kit code or data into the backend.
"""

import json
import subprocess
import sys
from collections import defaultdict
from collections.abc import Sequence
from pathlib import Path
from typing import Any

from tracex_engine.extract import extract_case
from tracex_engine.graph import CaseGraphStore, build_case_graph
from tracex_engine.matching import (
    DecisionError,
    LinkState,
    LinkStore,
    Matcher,
    RunResult,
    engine_result,
    write_engine_result,
)

KIT_DIR = Path(__file__).resolve().parents[4] / "data-kit"
BATCHES = ("b01", "b02")


def generate(out: Path) -> None:
    subprocess.run(  # noqa: S603 - fixed arguments, repository code
        [sys.executable, "-m", "datakit", "generate", "--tier", "small", "--out", str(out)],
        cwd=KIT_DIR,
        check=True,
        capture_output=True,
        timeout=120,
    )


def batch_cases(kit: Path, batch: str) -> list[str]:
    return sorted(p.name for p in (kit / "batches" / batch / "cases").iterdir())


def case_files(kit: Path, case_id: str, upto: str) -> dict[str, str]:
    """Every file of the case in batches up to and including `upto`."""
    files: dict[str, str] = {}
    for batch in BATCHES[: BATCHES.index(upto) + 1]:
        folder = kit / "batches" / batch / "cases" / case_id
        if folder.is_dir():
            for path in sorted(folder.iterdir()):
                files[path.name] = path.read_text("utf-8")
    return files


def load(store: CaseGraphStore, kit: Path, batch: str, only: Sequence[str] = ()) -> list[str]:
    """Write the cases a batch touches (rebuilt from all their files so far); their ids."""
    cases = [c for c in batch_cases(kit, batch) if not only or c in only]
    for case_id in cases:
        store.write_case(build_case_graph(extract_case(case_id, case_files(kit, case_id, batch))))
    return cases


# The kit's human step before b02 (data-kit 6, AC-15): an INVESTIGATOR rejects the AC-05 person
# pair (C-107 Jaswinder ~ C-108 Jasvinder). Steps 1-3 of scenario SC-AC15-AC25 (run b01, reject,
# run b02); the later reopen and confirm steps are API behaviour and are not applied here.
AC15_HARNESS = "SC-AC15-AC25"
AC15_CASES = frozenset({"C-107", "C-108"})


def harness_applied(upto: str) -> list[str]:
    """The `harness_applied` ids of a `run_batches` result up to `upto`."""
    return [AC15_HARNESS] if upto == "b02" else []


def reject_ac05_pair(graphs: CaseGraphStore, matcher: Matcher) -> None:
    """Apply the AC-15 REJECT: the one SUGGESTED person edge joining C-107 and C-108."""
    case_of = {
        e.entity_id: case_id
        for case_id in graphs.case_ids()
        if (graph := graphs.read_case(case_id)) is not None
        for e in graph.entities
    }
    [edge] = [
        e
        for e in matcher.links.edges()
        if e.entity_type.value == "PERSON"
        and {case_of[e.entity_a_id], case_of[e.entity_b_id]} == AC15_CASES
    ]
    record = matcher.apply_decision(
        edge.link_id,
        LinkState.SUGGESTED,
        LinkState.REJECTED,
        actor_user_id="kit-investigator",
        decision_id="kit-ac15-reject",
        reason_code=None,
        reason_text="AC-15 harness step",
    )
    assert not isinstance(record, DecisionError), record


def run_batches(
    graphs: CaseGraphStore, links: LinkStore, kit: Path, upto: str
) -> tuple[Matcher, list[RunResult]]:
    """Load and match b01, then (if asked) apply the AC-15 REJECT and match b02 on the cases it
    touched. Declare `harness_applied(upto)` in the result document."""
    matcher = Matcher(graphs, links)
    load(graphs, kit, "b01")
    results = [matcher.run_matching(input_case_ids=(), triggered_by="kit-harness")]
    if upto == "b02":
        reject_ac05_pair(graphs, matcher)
        touched = load(graphs, kit, "b02")
        results.append(matcher.run_matching(input_case_ids=touched, triggered_by="kit-harness"))
    return matcher, results


def score(kit: Path, document: dict[str, Any], workdir: Path) -> dict[str, Any]:
    """Run the reference scorer on a result document; its JSON report."""
    path = workdir / f"engine_result_{'_'.join(document['batches_loaded'])}.json"
    write_engine_result(path, document)
    done = subprocess.run(  # noqa: S603 - fixed arguments, repository code
        [
            sys.executable,
            "-m",
            "datakit",
            "score",
            "--ground-truth",
            str(kit / "ground_truth.json"),
            "--result",
            str(path),
            "--json",
        ],
        cwd=KIT_DIR,
        capture_output=True,
        timeout=120,
        check=False,
    )
    assert done.returncode in (0, 1), done.stderr.decode("utf-8", "replace")
    report: dict[str, Any] = json.loads(done.stdout)
    return report


def result_document(
    graphs: CaseGraphStore, links: LinkStore, batches: Sequence[str], last: RunResult
) -> dict[str, Any]:
    return engine_result(
        graphs,
        links,
        batches_loaded=batches,
        harness_applied=harness_applied(batches[-1]),
        run=last.run,
    )


def failures_by_link(report: dict[str, Any]) -> dict[str, set[str]]:
    """Expected-link id -> the failure kinds the scorer reported for it (`missed` included)."""
    found: dict[str, set[str]] = defaultdict(set)
    for item in report["missed_links"]:
        found[item["id"]].add("missed")
    for item in report["wrong_links"]:
        if item["id"] is not None:
            found[item["id"]].add(item["kind"])
    return found
